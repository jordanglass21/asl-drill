// Motion report over the full (gitignored) recordings. Skipped unless
// MOTION_EVAL is set: run `npm run eval:motion` locally after recording.
import { existsSync, readdirSync, readFileSync, writeFileSync } from "node:fs";
import { join } from "node:path";
import { isHit, falseMotion, replayTake, summarizeMotion, type EvalTake } from "./evaluate";

const ROOT = join(__dirname, "..", "..", "..");
const DATA = join(ROOT, "training", "data", "recordings");
const REPORT = join(ROOT, "training", "reports", "motion-v1.md");
const run = process.env.MOTION_EVAL && existsSync(DATA) ? describe : describe.skip;

interface RawTake {
  id: string;
  letter: string;
  kind?: EvalTake["kind"];
  camera: EvalTake["camera"];
  frames: EvalTake["frames"];
}

function loadTakes(): EvalTake[] {
  const seen = new Set<string>();
  const takes: EvalTake[] = [];
  for (const file of readdirSync(DATA).filter((f) => f.endsWith(".json")).sort()) {
    const data = JSON.parse(readFileSync(join(DATA, file), "utf8")) as { takes: RawTake[] };
    for (const t of data.takes) {
      if (seen.has(t.id)) continue;
      seen.add(t.id);
      takes.push({ id: t.id, label: t.letter, kind: t.kind ?? "letter", camera: t.camera, frames: t.frames });
    }
  }
  return takes;
}

run("motion detector on recorded takes", () => {
  it("writes the motion report", () => {
    const results = loadTakes().map((take) => replayTake(take));
    const { rows } = summarizeMotion(results);
    const lines = [
      "# Motion detector v1: report",
      "",
      "Generated by `npm run eval:motion` from every recorded take. Hits: J/Z takes fire their letter; double takes",
      "fire a double of their letter. False motion: a J or Z fired where none was signed. Stray doubles only matter",
      "on double letters, so they're listed for information.",
      "",
      "| Takes | Count | Hits | False J/Z | Stray doubles |",
      "|---|---|---|---|---|",
      ...rows.map((r) =>
        `| ${r.group} | ${r.takes} | ${["J", "Z", "doubles"].includes(r.group) ? `${r.hits} (${Math.round((r.hits / r.takes) * 100)}%)` : "–"} | ${r.falseMotion} | ${r.strayDoubles} |`,
      ),
      "",
      "## Misses and false alarms",
      "",
      ...results
        .filter((r) => (r.expected !== "none" && !isHit(r)) || falseMotion(r).length > 0)
        .map((r) => `- ${r.take.kind} ${r.take.label} (${r.take.id.slice(0, 8)}): expected ${r.expected}, got ${r.events.map((e) => (e.kind === "double" ? `double (${e.style})` : e.kind)).join(", ") || "nothing"}`),
      "",
      "## Doubles by style",
      "",
      ...results
        .filter((r) => r.expected === "double")
        .map((r) => `- ${r.take.label}: ${r.events.filter((e) => e.kind === "double").map((e) => (e.kind === "double" ? e.style : "")).join(", ") || "missed"}`),
      "",
    ];
    writeFileSync(REPORT, lines.join("\n"));
    console.log(lines.slice(6, 6 + rows.length + 2).join("\n"));
    expect(results.length).toBeGreaterThan(0);
  });
});
